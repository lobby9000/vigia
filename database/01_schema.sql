-- =============================================================================
-- Vigia | PostgreSQL schema (tables, constraints and indexes)
--
-- The official Postgres image runs every *.sql file in
-- /docker-entrypoint-initdb.d in alphabetical order the FIRST time the data
-- volume is created, so this file always runs before 02_views.sql.
--
-- Design notes
--   * Third normal form for reference data (teams -> applications).
--   * request_events is the high-volume fact table (one row per HTTP request
--     reported by a monitored application). Its indexes are designed around
--     the two real access paths: "one app in a time range" and "every app in
--     the last N minutes".
--   * Business rules live in CHECK constraints so that every client
--     (Java, Python, Django, psql) gets the same guarantees.
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- Reference data
-- -----------------------------------------------------------------------------
CREATE TABLE teams (
    id          INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(80)  NOT NULL UNIQUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE applications (
    id                  INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(50)   NOT NULL UNIQUE
                        CHECK (code ~ '^[a-z0-9][a-z0-9-]{2,49}$'),
    name                VARCHAR(120)  NOT NULL,
    team_id             INTEGER       NOT NULL REFERENCES teams (id),
    -- 1 = business critical, 3 = best effort
    tier                SMALLINT      NOT NULL CHECK (tier BETWEEN 1 AND 3),
    -- Availability objective, e.g. 0.99950 = 99.95 % of requests without 5xx
    slo_availability    NUMERIC(6, 5) NOT NULL DEFAULT 0.99900
                        CHECK (slo_availability > 0.9 AND slo_availability < 1),
    -- Latency objective: 95th percentile must stay under this value
    slo_latency_p95_ms  INTEGER       NOT NULL DEFAULT 800 CHECK (slo_latency_p95_ms > 0),
    -- SHA-256 (hex) of the ingestion API key. The key itself is never stored.
    api_key_hash        VARCHAR(64)   NOT NULL UNIQUE,
    active              BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- PostgreSQL does NOT index foreign keys automatically. Joins and
-- "apps of team X" lookups need this one.
CREATE INDEX idx_applications_team ON applications (team_id);

-- -----------------------------------------------------------------------------
-- Telemetry: one row per request reported by a monitored application
-- -----------------------------------------------------------------------------
CREATE TABLE request_events (
    id           BIGINT       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    app_id       INTEGER      NOT NULL REFERENCES applications (id),
    occurred_at  TIMESTAMPTZ  NOT NULL,
    received_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    endpoint     VARCHAR(200) NOT NULL,
    http_method  VARCHAR(7)   NOT NULL
                 CHECK (http_method IN ('GET', 'POST', 'PUT', 'PATCH', 'DELETE')),
    status_code  SMALLINT     NOT NULL CHECK (status_code BETWEEN 100 AND 599),
    latency_ms   INTEGER      NOT NULL CHECK (latency_ms >= 0),
    region       VARCHAR(30)  NOT NULL
);

-- Main access path: one application, one time range.
-- INCLUDE makes it a covering index: health queries only need these columns,
-- so PostgreSQL can answer them with an index-only scan (no heap visits).
CREATE INDEX idx_events_app_time
    ON request_events (app_id, occurred_at)
    INCLUDE (status_code, latency_ms);

-- Partial index: only server errors (a tiny fraction of rows), which makes
-- "latest errors of app X" queries cheap without indexing every request.
CREATE INDEX idx_events_app_errors
    ON request_events (app_id, occurred_at)
    WHERE status_code >= 500;

-- BRIN index: a few kilobytes that summarise blocks of an append-only table
-- whose physical order follows time. Ideal for "all apps, last hour" scans.
CREATE INDEX idx_events_occurred_brin
    ON request_events USING BRIN (occurred_at);

-- -----------------------------------------------------------------------------
-- Incidents: opened by people (Django admin) or by the anomaly detector
-- -----------------------------------------------------------------------------
CREATE TABLE incidents (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id           INTEGER       NOT NULL REFERENCES applications (id),
    title            VARCHAR(200)  NOT NULL,
    description      TEXT,
    severity         VARCHAR(4)    NOT NULL CHECK (severity IN ('SEV1', 'SEV2', 'SEV3')),
    status           VARCHAR(12)   NOT NULL DEFAULT 'OPEN'
                     CHECK (status IN ('OPEN', 'ACKNOWLEDGED', 'RESOLVED')),
    source           VARCHAR(20)   NOT NULL DEFAULT 'manual'
                     CHECK (source IN ('manual', 'anomaly_detector')),
    -- Time window of the anomaly that triggered the incident (detector only)
    window_start     TIMESTAMPTZ,
    window_end       TIMESTAMPTZ,
    -- MongoDB ObjectId (24 hex chars) of the anomaly report, if any
    report_id        VARCHAR(24),
    opened_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    acknowledged_at  TIMESTAMPTZ,
    resolved_at      TIMESTAMPTZ,
    CONSTRAINT chk_incident_window
        CHECK (window_start IS NULL OR window_end IS NULL OR window_end >= window_start),
    -- A resolved incident always has a resolution time, and only resolved ones do.
    CONSTRAINT chk_incident_resolution
        CHECK ((status = 'RESOLVED') = (resolved_at IS NOT NULL))
);

CREATE INDEX idx_incidents_opened ON incidents (opened_at DESC);

-- Partial index for the most common question: "what is still open for app X?"
CREATE INDEX idx_incidents_app_unresolved
    ON incidents (app_id, opened_at DESC)
    WHERE status <> 'RESOLVED';

-- -----------------------------------------------------------------------------
-- Users of the analytics API (JWT login). Django keeps its own auth tables.
-- -----------------------------------------------------------------------------
CREATE TABLE api_users (
    id             INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(50)   NOT NULL UNIQUE,
    password_hash  VARCHAR(255)  NOT NULL,
    role           VARCHAR(10)   NOT NULL CHECK (role IN ('viewer', 'admin')),
    active         BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now()
);

COMMIT;
